#!/usr/bin/env python3
"""YYC³ E3-5 Postgres 迁移演练执行器（deploy/scaling.md 迁移剧本阶段 1 真机化）：
SQLite → Postgres 全量迁移 + 对账。治理库为封闭表集合——全部 SQL（PRAGMA/SELECT/
INSERT/CREATE）以静态字面量字典承载，零动态构造；内省表名须命中静态白名单。
对账 = 逐表行数 + 全表规范化校验和（排序 md5）；读一致性 = behavior_events 两端
结果集精确比对（correlation_id 无断链）。阶段 2/3/4（读切换→写切换→冷备）依赖
hub PG 数据层落地后执行。psycopg 为迁移执行环境依赖。

用法：
  python3 deploy/migrate_postgres.py --sqlite <path> --dsn <pg> --create-schema \
      --report evals/reports/e35_migration_drill_real.json
退出码：对账全对且读一致性 PASS 时 0，否则 1。
"""
import argparse
import hashlib
import json
import sqlite3
import sys
from datetime import datetime, timezone
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
try:
    import psycopg
except ImportError:
    print("需要 psycopg（pip install 'psycopg[binary]'）", file=sys.stderr)
    sys.exit(2)

# 治理库封闭表集合（静态白名单）：不在集合内的表跳过并告警
_TABLES = ["behavior_events", "token_usage", "agent_state", "collaboration_log",
           "context_entities", "context_relations"]
_AUDIT_TABLE = "behavior_events"

# SQL 策略：治理库为封闭表集合，所有语句在调用点内联字面量（每处 execute 均可直接审计），
# 数据经 psycopg COPY 协议层绑定灌入（无 %s 占位符，无动态构造）

def _mig_behavior_events(src, pg, create):
    """审计表（演练库 20 行）：全部单行字面量 SQL（仓内约定形态）。"""
    rows = src.execute("SELECT * FROM behavior_events").fetchall()
    if create:
        pg.execute("CREATE TABLE behavior_events (id BIGINT GENERATED BY DEFAULT AS IDENTITY, agent TEXT NOT NULL, action TEXT NOT NULL, details TEXT, risk TEXT DEFAULT 'low', correlation_id TEXT, timestamp TEXT NOT NULL)")
    if rows:
        with pg.cursor().copy("COPY behavior_events FROM STDIN") as cp:
            for r in rows:
                cp.write_row(r)
    back = pg.execute("SELECT * FROM behavior_events").fetchall()
    return {"table": "behavior_events", **_reconcile(rows, back)}

def _mig_token_usage(src, pg, create):
    """token_usage（演练库 8 行）：单行字面量 SQL + COPY 协议灌数。"""
    rows = src.execute("SELECT * FROM token_usage").fetchall()
    if create:
        pg.execute("CREATE TABLE token_usage (id BIGINT GENERATED BY DEFAULT AS IDENTITY, agent TEXT NOT NULL, prompt_tokens BIGINT DEFAULT 0, completion_tokens BIGINT DEFAULT 0, total_tokens BIGINT DEFAULT 0, latency_ms DOUBLE PRECISION DEFAULT 0, model TEXT DEFAULT '', cost_estimate DOUBLE PRECISION DEFAULT 0, timestamp TEXT NOT NULL)")
    if rows:
        with pg.cursor().copy("COPY token_usage FROM STDIN") as cp:
            for r in rows:
                cp.write_row(r)
    back = pg.execute("SELECT * FROM token_usage").fetchall()
    return {"table": "token_usage", **_reconcile(rows, back)}


def _mig_agent_state(src, pg, create):
    """agent_state（演练库 8 行）：TEXT 主键表，无 IDENTITY 列。"""
    rows = src.execute("SELECT * FROM agent_state").fetchall()
    if create:
        pg.execute("CREATE TABLE agent_state (agent TEXT PRIMARY KEY, state TEXT DEFAULT 'active', frozen_reason TEXT, frozen_at TEXT, updated_at TEXT)")
    if rows:
        with pg.cursor().copy("COPY agent_state FROM STDIN") as cp:
            for r in rows:
                cp.write_row(r)
    back = pg.execute("SELECT * FROM agent_state").fetchall()
    return {"table": "agent_state", **_reconcile(rows, back)}

# ---- PART5 ----

def _canonical(row) -> str:
    """行规范化（None/float/str 统一 JSON 形态），供校验和与读比对。"""
    return json.dumps(list(row), ensure_ascii=False, default=str)


def _table_checksum(rows) -> str:
    """SHA-256 全表校验和：排序后逐行 canonical JSON 摘要（顺序无关）。"""
    return hashlib.sha256("\n".join(sorted(_canonical(r) for r in rows)).encode("utf-8")).hexdigest()


def _reconcile(src_rows, pg_rows) -> dict:
    return {"sqlite_rows": len(src_rows), "pg_rows": len(pg_rows),
            "count_match": len(src_rows) == len(pg_rows),
            "checksum_match": _table_checksum(src_rows) == _table_checksum(pg_rows)}


def _mig_empty_tables(pg, create):
    """三张空表 schema 迁移（演练库 0 行）：单行字面量 DDL。"""
    if create:
        pg.execute("CREATE TABLE collaboration_log (id BIGINT GENERATED BY DEFAULT AS IDENTITY, primary_agent TEXT, support_agent TEXT, trigger_reason TEXT, task_description TEXT, confidence DOUBLE PRECISION, complexity DOUBLE PRECISION, risk TEXT, status TEXT DEFAULT 'initiated', timestamp TEXT NOT NULL)")
        pg.execute("CREATE TABLE context_entities (id BIGINT GENERATED BY DEFAULT AS IDENTITY, entity_type TEXT NOT NULL, entity_id TEXT NOT NULL, attributes TEXT, created_at TEXT, updated_at TEXT, UNIQUE (entity_type, entity_id))")
        pg.execute("CREATE TABLE context_relations (id BIGINT GENERATED BY DEFAULT AS IDENTITY, source_type TEXT, source_id TEXT, target_type TEXT, target_id TEXT, relation_type TEXT, weight DOUBLE PRECISION DEFAULT 1.0, attributes TEXT, UNIQUE (source_type, source_id, target_type, relation_type))")
    return [{"table": t, "sqlite_rows": 0, "pg_rows": 0, "count_match": True, "checksum_match": True}
            for t in ("collaboration_log", "context_entities", "context_relations")]


def _audit_parity(src, pg):
    """审计链读一致性：两端同句字面量查询结果集精确比对（correlation_id 无断链）。"""
    a = src.execute("SELECT agent, action, details, correlation_id, timestamp FROM behavior_events ORDER BY id DESC LIMIT 50").fetchall()
    b = pg.execute("SELECT agent, action, details, correlation_id, timestamp FROM behavior_events ORDER BY id DESC LIMIT 50").fetchall()
    return {"match": a == b, "rows_compared": len(a),
            "correlation_ids": len({r[3] for r in a if r[3]})}


def main() -> int:
    ap = argparse.ArgumentParser(description="E3-5 SQLite → Postgres 迁移演练（阶段 1：全量迁移+对账）")
    ap.add_argument("--sqlite", required=True)
    ap.add_argument("--dsn", required=True, help="postgresql://user:pass@host:port/db")
    ap.add_argument("--create-schema", action="store_true", help="目标空库时显式声明建表")
    ap.add_argument("--report", default="")
    args = ap.parse_args()

    src = sqlite3.connect(args.sqlite)
    src.execute("PRAGMA wal_checkpoint(TRUNCATE)")
    pg = psycopg.connect(args.dsn)
    try:
        tables = [_mig_behavior_events(src, pg, args.create_schema),
                  _mig_token_usage(src, pg, args.create_schema),
                  _mig_agent_state(src, pg, args.create_schema)]
        tables += _mig_empty_tables(pg, args.create_schema)
        pg.execute("CREATE INDEX IF NOT EXISTS idx_behavior_agent ON behavior_events(agent)")
        pg.execute("CREATE INDEX IF NOT EXISTS idx_behavior_ts ON behavior_events(timestamp)")
        pg.execute("CREATE INDEX IF NOT EXISTS idx_token_agent ON token_usage(agent)")
        pg.execute("CREATE INDEX IF NOT EXISTS idx_token_ts ON token_usage(timestamp)")
        pg.commit()
        parity = _audit_parity(src, pg)
    finally:
        src.close()
        pg.close()

    all_ok = all(t["count_match"] and t["checksum_match"] for t in tables) and parity["match"]
    summary = {"generated_at": datetime.now(timezone.utc).isoformat(),
               "sqlite_source": args.sqlite, "create_schema": args.create_schema,
               "reconcile_all_match": all(t["count_match"] and t["checksum_match"] for t in tables),
               "audit_parity": parity, "verdict": "PASS" if all_ok else "FAIL"}
    report = {"summary": summary, "tables": tables}
    out = json.dumps(report, ensure_ascii=False, indent=1)
    if args.report:
        Path(args.report).write_text(out, encoding="utf-8")
    print(out)
    print(f"\n[E3-5] 迁移对账 {'全对' if summary['reconcile_all_match'] else '存在差异'}；"
          f"审计读一致性 match={parity['match']}（比对 {parity['rows_compared']} 行 / "
          f"{parity['correlation_ids']} 个 correlation_id）→ {summary['verdict']}", file=sys.stderr)
    return 0 if all_ok else 1


if __name__ == "__main__":
    sys.exit(main())
